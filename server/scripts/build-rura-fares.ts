// Rebuilds src/services/geo/rura/fares.data.ts from the official RURA inter-city fare CSVs.
// Run after replacing the CSVs with a newer tariff:  npm run rura:build
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { canonicalStop } from '../src/services/geo/rura/stops.js';

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/services/geo/rura');
const EN = 'Intercity_Transport_Fares_2026_EN.csv', RW = 'Ibiciro_Ingendo_Mu_Ntara_2026_RW.csv';

function parseCsv(text: string): string[][] {
  const rows: string[][] = []; let row: string[] = [], cell = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; } else if (c === '"') q = false; else cell += c; }
    else if (c === '"') q = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n' || c === '\r') { if (c === '\r' && text[i + 1] === '\n') i++; row.push(cell); cell = ''; if (row.some((x) => x.trim())) rows.push(row); row = []; }
    else cell += c;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows;
}

const en = parseCsv(fs.readFileSync(path.join(dir, EN), 'utf8')).slice(1);
const rw = parseCsv(fs.readFileSync(path.join(dir, RW), 'utf8')).slice(1);
if (en.length !== rw.length) throw new Error(`Row count differs: EN ${en.length}, RW ${rw.length}`);

const dirs: { province_en: string; province_rw: string; name_en: string; name_rw: string }[] = [];
const fares: [string, string, string, number, number][] = [];
en.forEach((r, i) => {
  const [no, province, direction, , from, to, via, fare] = r;
  const k = rw[i];
  if (k[4] !== from || k[5] !== to || k[6] !== via || k[7] !== fare) throw new Error(`Row ${no}: EN and RW data differ`);
  const amount = Number(fare);
  if (!Number.isFinite(amount) || amount <= 0) throw new Error(`Row ${no}: bad fare "${fare}"`);
  let d = dirs.findIndex((x) => x.name_en === direction && x.province_en === province);
  if (d < 0) { dirs.push({ province_en: province, province_rw: k[1], name_en: direction, name_rw: k[2] }); d = dirs.length - 1; }
  const c = (s: string) => (s ? canonicalStop(s, province) : '');
  fares.push([c(from), c(to), c(via), amount, d]);
});

const out = `// GENERATED by scripts/build-rura-fares.ts from ${EN} / ${RW}. Do not edit by hand.
// RURA (Rwanda Utilities Regulatory Authority) inter-city public transport fares, 2026, RWF per passenger, one way.
export const RURA_TARIFF = { year: 2026, routes: ${fares.length} } as const;
export interface RuraDirection { province_en: string; province_rw: string; name_en: string; name_rw: string }
export const RURA_DIRECTIONS: RuraDirection[] = ${JSON.stringify(dirs, null, 1)};
/** [from, to, via ('' = direct), fare RWF, index in RURA_DIRECTIONS] */
export const RURA_FARES: [string, string, string, number, number][] = [
${fares.map((f) => '  ' + JSON.stringify(f)).join(',\n')},
];
`;
fs.writeFileSync(path.join(dir, 'fares.data.ts'), out);
console.log(`Wrote ${fares.length} fares in ${dirs.length} directions.`);
