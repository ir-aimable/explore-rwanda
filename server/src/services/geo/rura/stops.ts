/** Spellings in the RURA table that refer to one stop. `province` disambiguates repeated names. */
export function canonicalStop(raw: string, province: string): string {
  const n = raw.trim();
  if (n === 'Congo Nile') return 'Congo-Nile';
  if (n === 'Nyanza (South)') return 'Nyanza';
  if (n === 'Rukomo') return 'Rukomo (Nyagatare)';
  if (n === 'Kirambo') return province.startsWith('Northern') ? 'Kirambo (Burera)' : 'Kirambo (Nyamasheke)';
  return n;
}
